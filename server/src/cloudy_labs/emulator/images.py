"""Maintain the Amazon Linux 2023 instance image and the AMI catalog that points Floci at it.

    uv run python -m cloudy_labs.emulator.images sync-catalog   # after changing Floci's image in compose.yaml
    uv run python -m cloudy_labs.emulator.images bump-base      # pick up a newer amazonlinux:2023
"""

import argparse
import re
import struct
import sys
import tempfile
from pathlib import Path

import yaml

from . import stack
from .docker import DockerError, docker

CATALOG_FILE = stack.COMPOSE_FILE.with_name("ec2-image-catalog.yaml")
DOCKERFILE = stack.AL2023_DIR / "Dockerfile"
STACK_FILE = Path(stack.__file__)
UPSTREAM_AL2023 = "public.ecr.aws/amazonlinux/amazonlinux:2023"
# Floci is a native binary; its resources are stored verbatim, each after a little-endian length.
CATALOG_START = b"defaultDockerImage:"
FROM_LINE = re.compile(r"^FROM (\S+)@(sha256:[0-9a-f]{64})$", re.M)
VERSION_LINE = re.compile(r"^AL2023_VERSION = (\d+)$", re.M)


def floci_image() -> str:
    return yaml.safe_load(stack.COMPOSE_FILE.read_text())["services"]["floci"]["image"]


def embedded_catalog(image: str) -> str:
    """The AMI catalog built into a Floci image (`ec2/image-catalog.yaml` in its sources)."""
    container = docker("create", image).strip()
    try:
        with tempfile.TemporaryDirectory() as tmp:
            binary = Path(tmp) / "application"
            docker("cp", "-q", f"{container}:/app/application", str(binary))
            data = binary.read_bytes()
    finally:
        docker("rm", container)
    if data.count(CATALOG_START) != 1:
        raise DockerError(f"expected one AMI catalog in {image}, found {data.count(CATALOG_START)}")
    start = data.index(CATALOG_START)
    (length,) = struct.unpack("<i", data[start - 4 : start])
    text = data[start : start + length].decode()
    if not isinstance(yaml.safe_load(text).get("images"), list):
        raise DockerError(f"the AMI catalog found in {image} has no images list")
    return text


def render_catalog(upstream: str, image: str, version: int) -> str:
    """Floci's catalog with Amazon Linux 2023 AMIs pointed at the image built for their architecture."""
    head, *entries = re.split(r"(?m)^(?=  - imageId: )", upstream)
    for i, entry in enumerate(entries):
        if f"    dockerImage: {UPSTREAM_AL2023}\n" in entry:
            arch = re.search(r"(?m)^    architecture: (\S+)$", entry).group(1)
            if arch not in stack.AL2023_PLATFORMS:
                raise ValueError(f"no Amazon Linux 2023 image is built for architecture {arch}")
            tag = stack.al2023_image(arch, version)
            entries[i] = entry.replace(f"    dockerImage: {UPSTREAM_AL2023}\n", f"    dockerImage: {tag}\n")
    header = f"""\
# Generated by `python -m cloudy_labs.emulator.images sync-catalog`; do not edit by hand.
# Floci's built-in AMI catalog from {image.split("@")[0]}, copied whole because a custom catalog
# replaces the built-in one. The only change: Amazon Linux 2023 entries use
# cloudy-labs/al2023:<version>-<architecture>, which `labctl up` builds from al2023/Dockerfile.
# Floci pulls an image for the entry's architecture, so each entry must name the tag built for
# that platform. The default (for unknown AMI IDs) has no architecture and stays upstream, so it
# works on any host but installs the IMDS packages at boot.
"""
    return header + head + "".join(entries)


def sync_catalog() -> None:
    image = floci_image()
    CATALOG_FILE.write_text(render_catalog(embedded_catalog(image), image, stack.AL2023_VERSION))
    print(f"wrote {CATALOG_FILE.name} from {image.split('@')[0]}")


def latest_base_digest(repository: str) -> str:
    return docker("buildx", "imagetools", "inspect", repository, "--format", "{{.Manifest.Digest}}").strip()


def bump_base(digest: str, force: bool = False) -> int | None:
    """Pin the Dockerfile to `digest` and move every al2023 tag to the next version.

    Returns the new version, or None when the digest is already pinned and `force` is not set.
    `force` bumps the version alone, for other changes to the Dockerfile.
    """
    dockerfile, source, catalog = DOCKERFILE.read_text(), STACK_FILE.read_text(), CATALOG_FILE.read_text()
    pinned = FROM_LINE.search(dockerfile)
    if pinned.group(2) == digest and not force:
        return None
    old = int(VERSION_LINE.search(source).group(1))
    new = old + 1
    for arch in stack.AL2023_PLATFORMS:
        if stack.al2023_image(arch, old) not in catalog:
            raise ValueError(f"{CATALOG_FILE.name} does not use {stack.al2023_image(arch, old)}")
        catalog = catalog.replace(stack.al2023_image(arch, old), stack.al2023_image(arch, new))
    DOCKERFILE.write_text(FROM_LINE.sub(f"FROM {pinned.group(1)}@{digest}", dockerfile, count=1))
    STACK_FILE.write_text(VERSION_LINE.sub(f"AL2023_VERSION = {new}", source, count=1))
    CATALOG_FILE.write_text(catalog)
    return new


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="python -m cloudy_labs.emulator.images", description=__doc__.split("\n")[0])
    commands = parser.add_subparsers(dest="command", required=True)
    commands.add_parser("sync-catalog", help="regenerate ec2-image-catalog.yaml from the Floci image in compose.yaml")
    bump = commands.add_parser("bump-base", help="pin the newest amazonlinux:2023 and bump the al2023 tag version")
    bump.add_argument("--force", action="store_true", help="bump the tag version even if the digest is unchanged")
    args = parser.parse_args(argv)
    try:
        if args.command == "sync-catalog":
            sync_catalog()
            return 0
        digest = latest_base_digest(UPSTREAM_AL2023)
        new = bump_base(digest, args.force)
    except (DockerError, ValueError) as e:
        print(f"error: {e}", file=sys.stderr)
        return 1
    if new is None:
        print(f"{UPSTREAM_AL2023} is already pinned at its latest digest {digest}")
        return 0
    old_tags = " ".join(stack.al2023_image(arch, new - 1) for arch in stack.AL2023_PLATFORMS)
    print(f"pinned {digest}; al2023 images are now version {new}")
    print("next: run the tests, then `labctl down` and `labctl up` to build the new images and reload the catalog")
    print(f"the old images can then go: docker image rm {old_tags}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

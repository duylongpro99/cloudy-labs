"""docs/coverage.md: what the platform covers, kind by kind, generated from the registry, Floci's
documented actions and the contract test results. `labctl coverage --matrix` rewrites it; a test
fails when the committed file is not what the generator writes."""

from __future__ import annotations

from pathlib import Path

from .evaluate import Evidence

DOC = Path(__file__).resolve().parents[4] / "docs" / "coverage.md"


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def _contract(ev: Evidence, kind: str) -> str:
    results = ev.contract_of(kind)
    if not results:
        return "not run"
    def ops(result: str) -> str:
        return ", ".join(sorted({r.get("op", "?") for r in results if r.get("result") == result}))
    worst = max((r.get("seconds", 0.0) for r in results), default=0.0)
    head = f"fail ({ops('fail')})" if ops("fail") else f"slow ({ops('slow')})" if ops("slow") else "pass"
    if any(r.get("result") == "no-op" for r in results):
        head += ", no delete op"
    return f"{head}, ≤{worst:.1f}s"


def _floci(ev: Evidence, service: str, status: str) -> str:
    entry = ev.floci_service(service)
    if entry is None:
        return "missing service"
    if status != "supported":
        return status
    if entry.get("complete"):
        return "supported (complete API)"
    if entry.get("unlisted"):
        return "supported (actions unlisted)"
    return f"supported ({len(entry['supported'])} actions)"


def render(ev: Evidence) -> str:
    rows = sorted((t for t in ev.registry.types if not t.structural and not t.test_only),
                  key=lambda t: (t.service, t.kind))
    lines = [
        "# Platform coverage",
        "",
        "<!-- Generated by `labctl coverage --matrix` from server/src/cloudy_labs/registry; do not edit. -->",
        "",
        f"Floci {ev.version} (`{ev.digest[:19]}…`). Floci status comes from the registry and from the action",
        f"tables of Floci's docs at that tag (`registry/floci-ops-{ev.version}.json`). The contract column is",
        "the last run of the contract tests (`registry/contract-results.json`)"
        + (f", recorded {ev.contract.get('date')} on `{str(ev.contract.get('floci_image_digest', ''))[:19]}…`."
           if ev.contract else "; they have not been run yet."),
        "",
        "Run `labctl coverage <lab>` for one lab's verdict and `labctl coverage --catalog <csv>` for the",
        "public catalog.",
        "",
        "| Service | Kind | Floci | Icon | Builder ops | Contract | Caveats |",
        "|---|---|---|---|---|---|---|",
    ]
    for t in rows:
        ops = ", ".join(f"`{op.id}`" for op in t.ops) or "—"
        caveats = "; ".join(f"**{c.code}**: {c.text}" for c in t.caveats)
        if t.floci.note:
            caveats = f"{t.floci.note}; {caveats}" if caveats else t.floci.note
        lines.append("| " + " | ".join(_cell(c) for c in (
            t.service, f"`{t.kind}`", _floci(ev, t.service, t.floci.status), t.view.icon or "outline",
            ops, _contract(ev, t.kind), caveats or "—")) + " |")
    services = sorted(s for s, e in ev.floci["services"].items() if not ev.kinds_of_service(s))
    lines += ["", f"Floci documents {len(services)} more services the registry has no kind for yet:", "",
              ", ".join(f"`{s}`" for s in services), ""]
    return "\n".join(lines)


def write(ev: Evidence, path: Path = DOC) -> bool:
    """Rewrite the matrix; True when the file changed."""
    text = render(ev)
    if path.is_file() and path.read_text() == text:
        return False
    path.write_text(text)
    return True
